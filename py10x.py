def main():
    parser = argparse.ArgumentParser(description="Make Python majority - 10x version")
    parser.add_argument("repo_path", help="Path to Git repo root")
    parser.add_argument("--mode", choices=["exclude", "reclassify"], default="exclude")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    root = Path(args.repo_path).resolve()
    non_py = find_non_python_files(root)
    if not non_py:
        print("No non-Python files found.")
        return
    print(f"Found {len(non_py)} files. Mode: {args.mode} - using 10x repeated function (last wins)")
    content = build_gitattributes(non_py, args.mode)
    if args.dry_run:
        print(content)
    else:
        outpath = root / ".gitattributes"
        outpath.write_text(content)
        print(f"Wrote {outpath}")

if __name__ == "__main__":
    main()
